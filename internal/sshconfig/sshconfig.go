// Package sshconfig owns the generated fragment ~/.ssh/dfm/config and the
// single Include line that pulls it into ~/.ssh/config.
package sshconfig

import (
	"fmt"
	"os"
	"path/filepath"
	"sort"
	"strings"
)

// IncludeLine is what the tool adds to the top of ~/.ssh/config. OpenSSH
// resolves relative Include paths against ~/.ssh.
const IncludeLine = "Include dfm/config"

// Entry describes one persona's contribution to the fragment.
type Entry struct {
	Persona   string
	GithubKey string // path of the github private key, empty when role absent
	AdminKey  string // path of the admin private key, empty when role absent
}

// Render builds the fragment. defaultPersona owns plain "github.com"; every
// other persona with a github key gets a "github.com-<persona>" alias that
// git remotes can use. macOS adds UseKeychain so the passphrase is remembered
// across reboots.
func Render(entries []Entry, defaultPersona string, macOS bool) string {
	sort.Slice(entries, func(i, j int) bool { return entries[i].Persona < entries[j].Persona })
	var b strings.Builder
	b.WriteString("# Generated by dfm. Edit ~/.ssh/config instead; this file is rewritten on every run.\n")
	keychain := ""
	if macOS {
		keychain = "  UseKeychain yes\n"
	}
	for _, e := range entries {
		if e.GithubKey == "" {
			continue
		}
		host := "github.com"
		extra := ""
		if e.Persona != defaultPersona {
			host = "github.com-" + e.Persona
			extra = "  HostName github.com\n"
		}
		fmt.Fprintf(&b, "\n# persona %s: GitHub\nHost %s\n%s  User git\n  IdentityFile %s\n  IdentitiesOnly yes\n  AddKeysToAgent yes\n%s",
			e.Persona, host, extra, e.GithubKey, keychain)
	}
	var admins []Entry
	for _, e := range entries {
		if e.AdminKey != "" {
			admins = append(admins, e)
		}
	}
	if len(admins) > 0 {
		b.WriteString("\n# admin keys offered to every host\nHost *\n")
		for _, e := range admins {
			fmt.Fprintf(&b, "  IdentityFile %s\n", e.AdminKey)
		}
		b.WriteString("  AddKeysToAgent yes\n" + keychain)
	}
	return b.String()
}

// WriteFragment writes the generated file with mode 0600.
func WriteFragment(path, content string) error {
	if err := os.MkdirAll(filepath.Dir(path), 0o700); err != nil {
		return err
	}
	return os.WriteFile(path, []byte(content), 0o600)
}

// EnsureInclude makes sure userCfg starts with IncludeLine. It returns true
// when the file was changed. Existing content is preserved below the line.
func EnsureInclude(userCfg string) (bool, error) {
	old, err := os.ReadFile(userCfg)
	if err != nil && !os.IsNotExist(err) {
		return false, err
	}
	if HasInclude(string(old)) {
		return false, nil
	}
	content := IncludeLine + "\n"
	if len(old) > 0 {
		content += "\n" + string(old)
	}
	if err := os.MkdirAll(filepath.Dir(userCfg), 0o700); err != nil {
		return false, err
	}
	return true, WriteOwned(userCfg, []byte(content), 0o600)
}

// WriteOwned writes a file the user owns even when an earlier tool left it
// read-only (the old installer did chmod 400 on everything in ~/.ssh), by
// lifting the mode first. Ownership is not changed.
func WriteOwned(path string, data []byte, mode os.FileMode) error {
	if st, err := os.Stat(path); err == nil && st.Mode().Perm()&0o200 == 0 {
		if err := os.Chmod(path, mode); err != nil {
			return err
		}
	}
	return os.WriteFile(path, data, mode)
}

// HasInclude reports whether the Include line is present and precedes any
// Host or Match block, which is required for it to apply globally.
func HasInclude(content string) bool {
	for _, line := range strings.Split(content, "\n") {
		t := strings.TrimSpace(line)
		if strings.EqualFold(t, IncludeLine) {
			return true
		}
		if strings.HasPrefix(strings.ToLower(t), "host ") || strings.HasPrefix(strings.ToLower(t), "match ") {
			return false
		}
	}
	return false
}
